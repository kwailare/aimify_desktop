import 'dart:async';

import 'package:flutter/services.dart';
import 'package:http/http.dart' as http;
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import '../../shared/utils/formatters.dart';
import '../auth/domain/auth_models.dart';

/// What every printed document shares: the fonts, the company's details and
/// logo, and the header, footer and money formatting built from them.
class DocumentKit {
  DocumentKit({required this.theme, required this.company, this.logo});

  final pw.ThemeData theme;
  final Organization company;

  /// The company logo, or `null` when there isn't one or it couldn't be
  /// fetched (offline): documents print fine without it.
  final pw.ImageProvider? logo;

  static const ink = PdfColor.fromInt(0xFF242424);
  static const muted = PdfColor.fromInt(0xFF6A737D);
  static const accent = PdfColor.fromInt(0xFFC9800C);
  static const rule = PdfColor.fromInt(0xFFE3E5E8);
  static const band = PdfColor.fromInt(0xFFF6F2EA);

  String money(double value) => currencyFormat.format(value);
  String date(DateTime value) => dateFormat.format(value);
  String dateTime(DateTime value) => dateTimeFormat.format(value);

  static Future<DocumentKit> load(Organization company) async {
    final regular = pw.Font.ttf(await rootBundle.load('assets/fonts/NotoSans-Regular.ttf'));
    final bold = pw.Font.ttf(await rootBundle.load('assets/fonts/NotoSans-Bold.ttf'));
    return DocumentKit(
      theme: pw.ThemeData.withFont(base: regular, bold: bold),
      company: company,
      logo: await _fetchLogo(company.logoUrl),
    );
  }

  static Future<pw.ImageProvider?> _fetchLogo(String? url) async {
    if (url == null || url.isEmpty) return null;
    try {
      final response = await http.get(Uri.parse(url)).timeout(const Duration(seconds: 6));
      if (response.statusCode != 200) return null;
      return pw.MemoryImage(Uint8List.fromList(response.bodyBytes));
    } catch (_) {
      return null;
    }
  }

  /// A new A4 document carrying [title] in its PDF properties.
  pw.Document document(String title) =>
      pw.Document(theme: theme, title: title, author: company.name, creator: 'Aimify');

  /// The company block on the left, the document's [title] and its
  /// [facts] (label/value pairs such as number and date) on the right.
  pw.Widget header(String title, List<(String, String)> facts) {
    final c = company;
    final details = [
      ?c.address,
      [?c.phone, ?c.email].join('  ·  '),
      if (c.registrationNumber != null) 'Reg. no. ${c.registrationNumber}',
      if (c.taxName != null && c.taxRate > 0) '${c.taxName} ${_plain(c.taxRate)}%',
    ].where((line) => line.trim().isNotEmpty).toList();

    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.stretch,
      children: [
        pw.Row(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            if (logo != null) ...[
              pw.Container(width: 56, height: 56, child: pw.Image(logo!, fit: pw.BoxFit.contain)),
              pw.SizedBox(width: 12),
            ],
            pw.Expanded(
              child: pw.Column(
                crossAxisAlignment: pw.CrossAxisAlignment.start,
                children: [
                  pw.Text(c.name, style: pw.TextStyle(fontSize: 15, fontWeight: pw.FontWeight.bold, color: ink)),
                  for (final line in details)
                    pw.Text(line, style: const pw.TextStyle(fontSize: 8.5, color: muted)),
                ],
              ),
            ),
            pw.SizedBox(width: 16),
            pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.end,
              children: [
                pw.Text(
                  title.toUpperCase(),
                  style: pw.TextStyle(fontSize: 16, fontWeight: pw.FontWeight.bold, color: accent, letterSpacing: 1),
                ),
                pw.SizedBox(height: 4),
                for (final (label, value) in facts)
                  pw.RichText(
                    text: pw.TextSpan(
                      children: [
                        pw.TextSpan(text: '$label  ', style: const pw.TextStyle(fontSize: 8.5, color: muted)),
                        pw.TextSpan(text: value, style: pw.TextStyle(fontSize: 9, fontWeight: pw.FontWeight.bold)),
                      ],
                    ),
                  ),
              ],
            ),
          ],
        ),
        pw.SizedBox(height: 10),
        pw.Container(height: 2, color: accent),
        pw.SizedBox(height: 14),
      ],
    );
  }

  pw.Widget footer(pw.Context context) => pw.Container(
        margin: const pw.EdgeInsets.only(top: 12),
        child: pw.Row(
          children: [
            pw.Expanded(
              child: pw.Text(
                'Generated by Aimify on ${dateTime(DateTime.now())}',
                style: const pw.TextStyle(fontSize: 7.5, color: muted),
              ),
            ),
            pw.Text(
              'Page ${context.pageNumber} of ${context.pagesCount}',
              style: const pw.TextStyle(fontSize: 7.5, color: muted),
            ),
          ],
        ),
      );

  /// A labelled block of lines (e.g. "Supplier" with its name and contact).
  pw.Widget infoBox(String label, List<String?> lines) => pw.Container(
        padding: const pw.EdgeInsets.all(10),
        decoration: pw.BoxDecoration(color: band, borderRadius: pw.BorderRadius.circular(4)),
        child: pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Text(label.toUpperCase(), style: pw.TextStyle(fontSize: 7.5, color: muted, fontWeight: pw.FontWeight.bold)),
            pw.SizedBox(height: 3),
            for (final (i, line) in lines.whereType<String>().where((l) => l.trim().isNotEmpty).indexed)
              pw.Text(
                line,
                style: i == 0
                    ? pw.TextStyle(fontSize: 10, fontWeight: pw.FontWeight.bold)
                    : const pw.TextStyle(fontSize: 8.5),
              ),
          ],
        ),
      );

  /// A table with a dark header row; [numeric] columns are right-aligned.
  pw.Widget table({
    required List<String> headers,
    required List<List<String>> rows,
    Set<int> numeric = const {},
    Map<int, pw.TableColumnWidth>? widths,
  }) =>
      pw.TableHelper.fromTextArray(
        headers: headers,
        data: rows,
        border: null,
        headerStyle: pw.TextStyle(fontSize: 8.5, fontWeight: pw.FontWeight.bold, color: PdfColors.white),
        headerDecoration: const pw.BoxDecoration(color: PdfColor.fromInt(0xFF1D2545)),
        cellStyle: const pw.TextStyle(fontSize: 8.5),
        cellHeight: 20,
        oddRowDecoration: const pw.BoxDecoration(color: PdfColor.fromInt(0xFFF7F7F8)),
        columnWidths: widths,
        headerAlignments: {
          for (var i = 0; i < headers.length; i++)
            i: numeric.contains(i) ? pw.Alignment.centerRight : pw.Alignment.centerLeft,
        },
        cellAlignments: {for (final i in numeric) i: pw.Alignment.centerRight},
      );

  /// Label/amount pairs aligned on the right, the last ones optionally bold.
  pw.Widget totals(List<(String, String)> lines, {int strongLast = 1}) => pw.Align(
        alignment: pw.Alignment.centerRight,
        child: pw.Container(
          width: 230,
          margin: const pw.EdgeInsets.only(top: 8),
          child: pw.Column(
            children: [
              for (final (i, (label, value)) in lines.indexed)
                pw.Container(
                  padding: const pw.EdgeInsets.symmetric(vertical: 3),
                  decoration: i >= lines.length - strongLast
                      ? const pw.BoxDecoration(border: pw.Border(top: pw.BorderSide(color: rule)))
                      : null,
                  child: pw.Row(
                    children: [
                      pw.Expanded(child: pw.Text(label, style: const pw.TextStyle(fontSize: 9, color: muted))),
                      pw.Text(
                        value,
                        style: pw.TextStyle(
                          fontSize: i >= lines.length - strongLast ? 10.5 : 9,
                          fontWeight: i >= lines.length - strongLast ? pw.FontWeight.bold : null,
                        ),
                      ),
                    ],
                  ),
                ),
            ],
          ),
        ),
      );

  /// Signature lines, e.g. "Received by" and "Checked by".
  pw.Widget signatures(List<String> labels) => pw.Padding(
        padding: const pw.EdgeInsets.only(top: 36),
        child: pw.Row(
          children: [
            for (final (i, label) in labels.indexed) ...[
              if (i > 0) pw.SizedBox(width: 30),
              pw.Expanded(
                child: pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: [
                    pw.Container(height: 1, color: ink),
                    pw.SizedBox(height: 3),
                    pw.Text(label, style: const pw.TextStyle(fontSize: 8, color: muted)),
                  ],
                ),
              ),
            ],
          ],
        ),
      );

  /// A faint diagonal word across the page (DRAFT, CANCELLED).
  pw.PageTheme pageTheme({String? watermark}) => pw.PageTheme(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.fromLTRB(36, 36, 36, 30),
        theme: theme,
        buildBackground: watermark == null
            ? null
            : (context) => pw.FullPage(
                  ignoreMargins: true,
                  child: pw.Center(
                    child: pw.Transform.rotateBox(
                      angle: 0.6,
                      child: pw.Text(
                        watermark,
                        style: pw.TextStyle(
                          fontSize: 90,
                          fontWeight: pw.FontWeight.bold,
                          color: const PdfColor(0.85, 0.2, 0.2, 0.12),
                        ),
                      ),
                    ),
                  ),
                ),
      );

  static String _plain(double value) => value == value.roundToDouble() ? value.toInt().toString() : value.toString();
}
